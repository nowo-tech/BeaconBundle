<?php

declare(strict_types=1);

namespace Nowo\BeaconBundle\DependencyInjection;

use Nowo\BeaconBundle\Messenger\RemoteRetry\RemoteCommand;
use Nowo\BeaconBundle\Scheduler\CheckInPolicy;
use Nowo\BeaconBundle\Support\IgnoredRequestPath;
use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

use function is_string;
use function str_starts_with;
use function trim;

/**
 * Defines the configuration tree for `nowo_beacon`.
 *
 * Point the DSN at any Beacon host (domain, subdomain, and optional port)
 * using `BEACON_DSN` (empty disables reporting).
 */
final class Configuration implements ConfigurationInterface
{
    public const ALIAS = 'nowo_beacon';

    /**
     * Builds the `nowo_beacon` configuration tree.
     */
    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder(self::ALIAS);
        $rootNode    = $treeBuilder->getRootNode();

        $rootNode
            ->children()
                ->booleanNode('enabled')
                    ->info('Master switch. When false, no events are sent even if DSN is set.')
                    ->defaultTrue()
                ->end()
                ->scalarNode('dsn')
                    ->info('Beacon DSN: https://PUBLIC_KEY:SECRET_KEY@host:port/PROJECT_ID_OR_UUID (empty disables sending). Prefer %env(default::BEACON_DSN)%.')
                    ->defaultValue('')
                ->end()
                ->scalarNode('environment')
                    ->info('Environment tag sent with events (e.g. prod, staging).')
                    ->defaultValue('%kernel.environment%')
                ->end()
                ->scalarNode('release')
                    ->info('Optional release / version string attached to events.')
                    ->defaultNull()
                ->end()
                ->scalarNode('server_name')
                    ->info('Hostname tag for events. Defaults to gethostname() when null.')
                    ->defaultNull()
                ->end()
                ->booleanNode('verify_peer')
                    ->info('TLS certificate verification. Set false for local self-signed Beacon HTTPS (dev only).')
                    ->defaultTrue()
                ->end()
                ->floatNode('timeout')
                    ->info('HTTP timeout in seconds for ingest requests.')
                    ->defaultValue(5.0)
                    ->min(0.1)
                ->end()
                ->arrayNode('transport')
                    ->info('Outbound Envelope delivery mode.')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->enumNode('mode')
                            ->info('sync = block on HTTP; async = start HTTP and finalize on kernel/console terminate; messenger = queue via Symfony Messenger (requires symfony/messenger).')
                            ->values(['sync', 'async', 'messenger'])
                            ->defaultValue('sync')
                        ->end()
                        ->arrayNode('retry')
                            ->info('Retry an Envelope POST when Beacon answers with a server error (5xx), waiting between attempts (exponential backoff with jitter; a Retry-After header is honoured). Applies to every mode; set max_retries to 0 to disable.')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->integerNode('max_retries')
                                    ->info('Extra attempts after the first one (0 = no retry).')
                                    ->defaultValue(2)
                                    ->min(0)
                                    ->max(10)
                                ->end()
                                ->integerNode('delay_ms')
                                    ->info('Wait before the first retry, in milliseconds.')
                                    ->defaultValue(500)
                                    ->min(0)
                                ->end()
                                ->floatNode('multiplier')
                                    ->info('Factor applied to the wait before each further retry.')
                                    ->defaultValue(2.0)
                                    ->min(1.0)
                                ->end()
                                ->integerNode('max_delay_ms')
                                    ->info('Upper bound of one wait, in milliseconds (0 = no bound).')
                                    ->defaultValue(5000)
                                    ->min(0)
                                ->end()
                                ->floatNode('jitter')
                                    ->info('Random variation applied to each wait (0.0–1.0).')
                                    ->defaultValue(0.1)
                                    ->min(0.0)
                                    ->max(1.0)
                                ->end()
                                ->arrayNode('status_codes')
                                    ->info('HTTP status codes from Beacon that trigger a retry.')
                                    ->integerPrototype()->min(500)->max(599)->end()
                                    ->defaultValue([500, 502, 503, 504])
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->booleanNode('register_error_listener')
                    ->info('When true, register a kernel.exception listener that reports uncaught exceptions.')
                    ->defaultTrue()
                ->end()
                ->arrayNode('ignore_exceptions')
                    ->info('FQCN list of exception classes that must not be reported by the error listener.')
                    ->scalarPrototype()->end()
                    ->defaultValue([])
                ->end()
                ->arrayNode('ignore_paths')
                    ->info('HTTP path prefixes skipped by the exception listener and auto HTTP transactions. Trailing slashes are ignored. Defaults match Beacon host infra exclusions (profiler, WDT, build, assets, health) plus Chrome DevTools Appspecific probe.')
                    ->scalarPrototype()->end()
                    ->defaultValue(IgnoredRequestPath::DEFAULTS)
                ->end()
                ->booleanNode('register_console_listener')
                    ->info('When true, report uncaught console command errors (ConsoleEvents::ERROR).')
                    ->defaultTrue()
                ->end()
                ->booleanNode('register_messenger_listener')
                    ->info('When true and symfony/messenger is installed, report WorkerMessageFailedEvent failures that will not retry.')
                    ->defaultTrue()
                ->end()
                ->booleanNode('register_fatal_handler')
                    ->info('When true, register a shutdown function that reports fatal PHP errors (E_ERROR, E_PARSE, …).')
                    ->defaultTrue()
                ->end()
                ->booleanNode('register_php_warning_handler')
                    ->info('When true, capture PHP warnings/notices as Beacon issues without converting them to exceptions (request continues).')
                    ->defaultTrue()
                ->end()
                ->arrayNode('php_warning_handler')
                    ->info('Options for register_php_warning_handler.')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('continue')
                            ->info('When true (default), handled warnings are reported and not rethrown — the request keeps running even under Symfony debug ErrorHandler.')
                            ->defaultTrue()
                        ->end()
                        ->booleanNode('capture_silenced')
                            ->info('When true, also report @-silenced warnings/notices.')
                            ->defaultFalse()
                        ->end()
                        ->arrayNode('levels')
                            ->info('PHP error kinds to capture: warning, user_warning, notice, user_notice, deprecated, user_deprecated, core_warning, compile_warning. Empty = default warnings+notices (no deprecations).')
                            ->scalarPrototype()->end()
                            ->defaultValue([])
                        ->end()
                    ->end()
                ->end()
                ->booleanNode('include_scheduler_context')
                    ->info('When true and a Messenger failure envelope carries Symfony Scheduler ScheduledStamp, attach extra.scheduler (name, recurring id, trigger, triggered_at). Never attaches the message body.')
                    ->defaultTrue()
                ->end()
                ->arrayNode('messenger')
                    ->info('Opt-in Messenger worker observability (requires symfony/messenger). Final failures are always reported by register_messenger_listener.')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('transactions')
                            ->info('Send one performance transaction per handled message (op queue.process, status ok/failed/retry, handler, transport). Doctrine/HttpClient spans are attached when instrumentation is enabled.')
                            ->defaultFalse()
                        ->end()
                        ->floatNode('transaction_sample_rate')
                            ->info('Fraction of messages that send a transaction (0.0–1.0).')
                            ->defaultValue(1.0)
                            ->min(0.0)
                            ->max(1.0)
                        ->end()
                        ->booleanNode('report_retries')
                            ->info('Send a warning event (retry_state will_retry) when a handler fails and Messenger will retry the message.')
                            ->defaultFalse()
                        ->end()
                        ->booleanNode('report_recovered')
                            ->info('Send an info event (retry_state recovered) when a message succeeds after at least one retry.')
                            ->defaultFalse()
                        ->end()
                        ->floatNode('retry_sample_rate')
                            ->info('Fraction of retry / recovered events that are sent (0.0–1.0).')
                            ->defaultValue(1.0)
                            ->min(0.0)
                            ->max(1.0)
                        ->end()
                        ->floatNode('worker_memory_warning_ratio')
                            ->info('When set (e.g. 0.8), warn once per worker process when memory usage reaches this fraction of PHP memory_limit. Null disables.')
                            ->defaultNull()
                            ->min(0.05)
                            ->max(1.0)
                        ->end()
                        ->arrayNode('ignore_message_classes')
                            ->info('Message FQCNs (subclasses / interfaces match) that the Messenger failure, retry and transaction listeners never report. Beacon\'s own SendBeaconEnvelopeMessage is always skipped.')
                            ->scalarPrototype()->end()
                            ->defaultValue([])
                        ->end()
                        ->arrayNode('failure_transports')
                            ->info('Transport names flagged as failure transports by nowo:beacon:messenger-report (and the default of remote_retry.failure_transports).')
                            ->scalarPrototype()->end()
                            ->defaultValue(['failed'])
                        ->end()
                        ->arrayNode('remote_retry')
                            ->info('Retry or discard one failed message from the Beacon UI: workers poll Beacon (outbound HTTPS only) for signed, expiring commands. Off by default; needs a Beacon worker key and a Beacon that supports it.')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')
                                    ->info('Poll Beacon for remote Messenger commands (requires symfony/messenger, BEACON_DSN and worker_key).')
                                    ->defaultFalse()
                                ->end()
                                ->scalarNode('worker_key')
                                    ->info('Beacon worker key (bwk_…, Beacon → Settings → Alerts → Remote Messenger commands). Keep it in an env var; required when enabled.')
                                    ->defaultValue('%env(default::BEACON_WORKER_KEY)%')
                                ->end()
                                ->arrayNode('allowed_actions')
                                    ->info('Actions this app accepts: retry and / or discard (e.g. [retry] forbids remote discards).')
                                    ->scalarPrototype()
                                        ->validate()
                                            ->ifNotInArray(RemoteCommand::ACTIONS)
                                            ->thenInvalid('Invalid nowo_beacon.messenger.remote_retry.allowed_actions entry %s (allowed: retry, discard).')
                                        ->end()
                                    ->end()
                                    ->defaultValue(RemoteCommand::ACTIONS)
                                ->end()
                                ->arrayNode('failure_transports')
                                    ->info('Failure transports commands may act on (empty = messenger.failure_transports). They must find messages by id (Doctrine, Redis).')
                                    ->scalarPrototype()->end()
                                    ->defaultValue([])
                                ->end()
                                ->integerNode('poll_interval')
                                    ->info('Seconds between polls (10 … 600); Beacon may ask for longer with poll_after.')
                                    ->defaultValue(30)
                                    ->min(10)
                                    ->max(600)
                                ->end()
                                ->booleanNode('poll_in_workers')
                                    ->info('Poll from running messenger:consume workers between messages. False = only nowo:beacon:messenger-commands polls.')
                                    ->defaultTrue()
                                ->end()
                            ->end()
                            ->validate()
                                ->ifTrue(static fn (array $v): bool => (bool) $v['enabled'] && (!is_string($v['worker_key']) || trim($v['worker_key']) === ''))
                                ->thenInvalid('nowo_beacon.messenger.remote_retry.worker_key is required when remote_retry is enabled (use %%env(BEACON_WORKER_KEY)%%).')
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('scheduler')
                    ->info('Symfony Scheduler integration (requires symfony/scheduler).')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->arrayNode('check_ins')
                            ->info('Scheduler check-ins: a schedule catalog when a scheduler worker starts and one check-in per run (in_progress / ok / error), so Beacon detects missed, too long and failed runs. Off by default; enable it only with a Beacon that supports check-ins.')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')
                                    ->info('Send the schedule catalog and run check-ins (requires symfony/scheduler and symfony/messenger).')
                                    ->defaultFalse()
                                ->end()
                                ->arrayNode('max_runtime')
                                    ->info('Max runtime in seconds (1 … 604800) per message FQCN (subclasses / interfaces match) or command name (RunCommandMessage). #[BeaconCheckIn(maxRuntime: …)] on the message class wins.')
                                    ->useAttributeAsKey('name')
                                    ->normalizeKeys(false)
                                    ->integerPrototype()
                                        ->min(CheckInPolicy::MAX_RUNTIME_MIN)
                                        ->max(CheckInPolicy::MAX_RUNTIME_MAX)
                                    ->end()
                                    ->defaultValue([])
                                ->end()
                                ->arrayNode('ignore')
                                    ->info('Message FQCNs (subclasses / interfaces match) or command names that are never checked in nor listed in the catalog. #[BeaconCheckIn(enabled: …)] wins.')
                                    ->scalarPrototype()->end()
                                    ->defaultValue([])
                                ->end()
                                ->arrayNode('descriptions')
                                    ->info('Human description of a task (plain text, one line, ≤ 500 chars) per message FQCN (subclasses / interfaces match) or command name. #[BeaconCheckIn(description: …)] wins; the command description and docblock summaries are the fallbacks.')
                                    ->useAttributeAsKey('name')
                                    ->normalizeKeys(false)
                                    ->scalarPrototype()->end()
                                    ->defaultValue([])
                                ->end()
                                ->integerNode('catalog_refresh_hours')
                                    ->info('Re-send the schedule catalog from a running scheduler worker every N hours (1 … 168).')
                                    ->defaultValue(24)
                                    ->min(1)
                                    ->max(168)
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->booleanNode('auto_http_transaction')
                    ->info('When true, send a performance transaction for each main HTTP request (skips ignore_paths, ignore_routes and unsampled requests).')
                    ->defaultFalse()
                ->end()
                ->floatNode('http_transaction_sample_rate')
                    ->info('Fraction of main HTTP requests that send a transaction when auto_http_transaction is on (0.0–1.0).')
                    ->defaultValue(1.0)
                    ->min(0.0)
                    ->max(1.0)
                ->end()
                ->arrayNode('ignore_routes')
                    ->info('Route-name prefixes whose HTTP transactions are never sent (auto_http_transaction), e.g. ingest or polling routes.')
                    ->scalarPrototype()->end()
                    ->defaultValue([])
                ->end()
                ->scalarNode('before_send')
                    ->info('Optional service id of an invokable that receives the event/transaction payload array and returns the mutated array, or null to drop the send.')
                    ->defaultNull()
                ->end()
                ->arrayNode('instrumentation')
                    ->info('Opt-in automatic spans / breadcrumbs for Doctrine SQL and HttpClient requests.')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('doctrine')
                            ->info('When true and doctrine/dbal is installed, record SQL query spans and breadcrumbs.')
                            ->defaultFalse()
                        ->end()
                        ->booleanNode('http_client')
                            ->info('When true, decorate http_client to record outbound HTTP spans and breadcrumbs (Beacon Envelope calls are skipped).')
                            ->defaultFalse()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('monolog_handler')
                    ->info('Optional Monolog handler (requires monolog/monolog). Disabled by default.')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')
                            ->defaultFalse()
                        ->end()
                        ->scalarNode('level')
                            ->info('Minimum Monolog level to forward (e.g. error, warning).')
                            ->defaultValue('error')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('self_test')
                    ->info('Self-test producing real failures (console: nowo:beacon:self-test, always available).')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->arrayNode('http')
                            ->info('Optional JSON endpoint (import routes with type nowo_beacon). Disabled by default.')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')
                                    ->info('Register the self-test controller and routes (GET status, POST {path}/{kind} with CSRF).')
                                    ->defaultFalse()
                                ->end()
                                ->scalarNode('path')
                                    ->info('Route path of the self-test endpoint.')
                                    ->defaultValue('/_beacon/self-test')
                                    ->cannotBeEmpty()
                                    ->validate()
                                        ->ifTrue(static fn (mixed $path): bool => !is_string($path) || !str_starts_with($path, '/'))
                                        ->thenInvalid('nowo_beacon.self_test.http.path must start with "/" (got %s).')
                                    ->end()
                                ->end()
                                ->arrayNode('roles')
                                    ->info('Roles allowed to use the endpoint (any of them). Empty = no role check (protect the path with your firewall).')
                                    ->scalarPrototype()->end()
                                    ->defaultValue(['ROLE_ADMIN'])
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('send')
                    ->info('Opt-in/out switches for categories of context attached to outbound events.')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('environment')
                            ->info('Send environment tag.')
                            ->defaultTrue()
                        ->end()
                        ->booleanNode('release')
                            ->info('Send release / code version when configured.')
                            ->defaultTrue()
                        ->end()
                        ->booleanNode('server_name')
                            ->info('Send server hostname tag.')
                            ->defaultTrue()
                        ->end()
                        ->booleanNode('stacktrace')
                            ->info('Send stack frames and culprit for exceptions, and current stack for captureMessage().')
                            ->defaultTrue()
                        ->end()
                        ->booleanNode('request')
                            ->info('Attach current HTTP request (url/method/query) to events and transactions when a request is available.')
                            ->defaultTrue()
                        ->end()
                        ->booleanNode('user')
                            ->info('Send authenticated user summary (may include PII). Disabled by default.')
                            ->defaultFalse()
                        ->end()
                        ->booleanNode('runtime')
                            ->info('Send PHP runtime version in contexts.runtime.')
                            ->defaultTrue()
                        ->end()
                        ->booleanNode('framework')
                            ->info('Send Symfony version in contexts.framework when available.')
                            ->defaultTrue()
                        ->end()
                        ->booleanNode('os')
                            ->info('Send OS family/version in contexts.os.')
                            ->defaultTrue()
                        ->end()
                        ->booleanNode('client')
                            ->info('Attach client IP and User-Agent on HTTP events (PII). Disabled by default.')
                            ->defaultFalse()
                        ->end()
                        ->booleanNode('stack_vars')
                            ->info('Attach function argument summaries as frame vars (Sentry-compatible). May include PII; disabled by default. Requires send.stacktrace.')
                            ->defaultFalse()
                        ->end()
                    ->end()
                ->end()
            ->end();

        return $treeBuilder;
    }
}
